import base64
import binascii
import datetime
import hashlib

from odoo import _, api, models
from odoo.exceptions import UserError, ValidationError
from odoo.tools.misc import hash_sign

from odoo.addons.muk_mcp.core.tool import mcp_tool
from odoo.addons.muk_mcp.tools.descriptions import context_field, model_field
from odoo.addons.muk_mcp.tools.uri import attachment_uri

UPLOAD_SCOPE = 'muk_mcp_attachment.upload'
UPLOAD_TTL = datetime.timedelta(minutes=15)

_TARGET_PROPERTIES = {
    'model': model_field(),
    'res_id': {
        'type': 'integer',
        'description': 'ID of the record the file is attached to.',
    },
    'name': {
        'type': 'string',
        'description': 'File name including extension, e.g. "invoice.pdf".',
    },
    'mimetype': {
        'type': 'string',
        'description': 'Optional MIME type. Guessed from the content when omitted.',
    },
}
_SHA256 = {
    'type': 'string',
    'description': 'Lowercase hex SHA-256 of the raw file bytes (`sha256sum file`).',
}
_SIZE = {
    'type': 'integer',
    'description': 'Exact size of the raw file in bytes (`wc -c < file`).',
}


class MCPMixin(models.AbstractModel):
    _inherit = 'muk_mcp.mixin'

    @api.model
    def _mcp_attachment_check_target(self, model, res_id):
        """Assert the caller may attach files to ``model(res_id)``."""
        record = self._resolve_model(model).browse(int(res_id or 0))
        if not record.exists():
            raise UserError(_('%(m)s(%(id)s) does not exist.', m=model, id=res_id))
        self._mcp_assert_records_allowed(model, [record.id])
        record.check_access('write')
        return record

    @api.model
    def _mcp_attachment_verify(self, raw, size=None, sha256=None):
        """Raise when ``raw`` does not match the declared size or checksum."""
        if size is not None and len(raw) != int(size):
            raise ValidationError(
                _(
                    'Size mismatch: received %(got)s bytes, expected %(exp)s. '
                    'The file was truncated or corrupted in transit.',
                    got=len(raw),
                    exp=size,
                )
            )
        digest = hashlib.sha256(raw).hexdigest()
        if sha256 and digest != sha256.strip().lower():
            raise ValidationError(
                _(
                    'SHA-256 mismatch: received %(got)s, expected %(exp)s. '
                    'The file was corrupted in transit.',
                    got=digest,
                    exp=sha256,
                )
            )
        return digest

    @api.model
    def _mcp_attachment_create(self, model, res_id, name, raw, mimetype=None):
        """Create (or reuse an identical) attachment and describe it."""
        Attachment = self.env['ir.attachment']
        # Same bytes + name on the same record: return it instead of duplicating,
        # so a retried upload is idempotent.
        attachment = Attachment.search(
            [
                ('res_model', '=', model),
                ('res_id', '=', res_id),
                ('name', '=', name),
                ('checksum', '=', Attachment._compute_checksum(raw)),
            ],
            limit=1,
        )
        if not attachment:
            values = {'name': name, 'raw': raw, 'res_model': model, 'res_id': res_id}
            if mimetype:
                values['mimetype'] = mimetype
            attachment = Attachment.create(values)
        return {
            'id': attachment.id,
            'name': attachment.name,
            'mimetype': attachment.mimetype,
            'size': len(raw),
            'sha256': hashlib.sha256(raw).hexdigest(),
            'uri': attachment_uri(attachment.id),
        }

    @api.model
    @mcp_tool(
        name='upload_attachment',
        description=(
            'Attach a SMALL file (up to a few KB) to a record, passing its bytes '
            'as base64. Large base64 strings get corrupted when generated by a '
            'model, so for any real file (PDF, image, XML, spreadsheet...) use '
            'request_attachment_upload instead. Pass sha256 and size whenever '
            'you can: the upload is rejected if the decoded bytes do not match.'
        ),
        input_schema={
            'type': 'object',
            'properties': {
                **_TARGET_PROPERTIES,
                'content_base64': {
                    'type': 'string',
                    'description': 'File content encoded as standard base64.',
                },
                'sha256': _SHA256,
                'size': _SIZE,
                'context': context_field(),
            },
            'required': ['model', 'res_id', 'name', 'content_base64'],
        },
        category='write',
    )
    def _mcp_upload_attachment(
        self, model, res_id, name, content_base64, mimetype=None, sha256=None, size=None
    ):
        record = self._mcp_attachment_check_target(model, res_id)
        try:
            raw = base64.b64decode(''.join((content_base64 or '').split()), validate=True)
        except (binascii.Error, ValueError) as exc:
            raise ValidationError(_('content_base64 is not valid base64: %s', exc)) from exc
        self._mcp_attachment_verify(raw, size=size, sha256=sha256)
        return self._mcp_attachment_create(model, record.id, name, raw, mimetype)

    @api.model
    @mcp_tool(
        name='request_attachment_upload',
        description=(
            'Preferred way to attach a file to a record. Returns a one-off signed '
            'upload_url (valid 15 minutes) bound to this record, file name, size '
            'and SHA-256. Then send the raw bytes with: '
            "curl -sS -X PUT --data-binary @<file> '<upload_url>'. "
            'The server rejects the upload unless size and SHA-256 match, so the '
            'stored file is byte-identical to the local one. Compute them with '
            '`wc -c < file` and `sha256sum file` (macOS: `shasum -a 256 file`).'
        ),
        input_schema={
            'type': 'object',
            'properties': {
                **_TARGET_PROPERTIES,
                'size': _SIZE,
                'sha256': _SHA256,
                'context': context_field(),
            },
            'required': ['model', 'res_id', 'name', 'size', 'sha256'],
        },
        category='write',
    )
    def _mcp_request_attachment_upload(
        self, model, res_id, name, size, sha256, mimetype=None
    ):
        record = self._mcp_attachment_check_target(model, res_id)
        sha256 = (sha256 or '').strip().lower()
        if len(sha256) != 64 or set(sha256) - set('0123456789abcdef'):
            raise ValidationError(_('sha256 must be a 64-character hex digest.'))
        if int(size) <= 0:
            raise ValidationError(_('size must be a positive number of bytes.'))
        token = hash_sign(
            self.env(su=True),
            UPLOAD_SCOPE,
            {
                'uid': self.env.uid,
                'model': model,
                'res_id': record.id,
                'name': name,
                'mimetype': mimetype or '',
                'size': int(size),
                'sha256': sha256,
            },
            expiration=UPLOAD_TTL,
        )
        url = f'{self.get_base_url()}/mcp/attachment/upload/{token}'
        return {
            'upload_url': url,
            'method': 'PUT',
            'expires_in_seconds': int(UPLOAD_TTL.total_seconds()),
            'command': f"curl -sS -X PUT --data-binary @'<path/to/{name}>' '{url}'",
        }
